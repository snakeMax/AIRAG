"""Code map: what exists where, so changes look things up instead of guessing.

    python tools/codemap.py          writes CODEMAP.md (readable) and codemap.json (for tools/review.py)

Lists Python modules (functions/classes with signatures), HTTP routes, JS modules (exports/imports),
settings sections and keys, job kinds, AI tasks and i18n key counts.
"""
import ast
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))


def py_modules():
    out = {}
    for p in sorted((ROOT / "airag").rglob("*.py")):
        rel = p.relative_to(ROOT).as_posix()
        try:
            tree = ast.parse(p.read_text(encoding="utf-8"))
        except SyntaxError as e:
            out[rel] = {"error": str(e)}
            continue
        items = []
        for n in tree.body:
            if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)):
                args = [a.arg for a in n.args.args] + ([f"*{n.args.vararg.arg}"] if n.args.vararg else []) + \
                       [a.arg for a in n.args.kwonlyargs]
                items.append({"kind": "async def" if isinstance(n, ast.AsyncFunctionDef) else "def",
                              "name": n.name, "args": args, "line": n.lineno})
            elif isinstance(n, ast.ClassDef):
                methods = [m.name for m in n.body if isinstance(m, (ast.FunctionDef, ast.AsyncFunctionDef))]
                items.append({"kind": "class", "name": n.name, "methods": methods, "line": n.lineno})
        out[rel] = {"items": items}
    return out


ROUTE = re.compile(r'@app\.(get|post|put|delete)\("([^"]+)"')


ROUTER = re.compile(r'@router\.(get|post|put|delete)\("([^"]*)"')
PREFIX = re.compile(r'APIRouter\(\s*prefix\s*=\s*"([^"]+)"')


def routes():
    src = (ROOT / "airag" / "main.py").read_text(encoding="utf-8")
    out = {(m.group(1).upper(), m.group(2)) for m in ROUTE.finditer(src)}
    for p in (ROOT / "airag").rglob("*.py"):         # feature routers (e.g. airag/notes/api.py)
        s = p.read_text(encoding="utf-8")
        pre = PREFIX.search(s)
        if pre:
            out |= {(m.group(1).upper(), pre.group(1) + m.group(2)) for m in ROUTER.finditer(s)}
    return sorted(out, key=lambda r: (r[1], r[0]))


EXPORT = re.compile(r"^export\s+(?:async\s+)?(?:function\*?|const|let|class)\s+([A-Za-z_$][\w$]*)", re.M)
EXPORT_LIST = re.compile(r"^export\s*\{([^}]*)\}", re.M)
IMPORT = re.compile(r'^import\s*\{([^}]*)\}\s*from\s*"\./([^"]+)"', re.M)


def js_modules():
    out = {}
    for p in sorted((ROOT / "web" / "js").glob("*.js")):
        s = p.read_text(encoding="utf-8")
        exports = set(EXPORT.findall(s))
        for grp in EXPORT_LIST.findall(s):
            exports |= {x.split(" as ")[-1].strip() for x in grp.split(",") if x.strip()}
        imports = {}
        for names, mod in IMPORT.findall(s):
            imports.setdefault(mod, []).extend(x.split(" as ")[0].strip() for x in names.split(",") if x.strip())
        out[p.name] = {"exports": sorted(exports), "imports": imports}
    return out


def settings():
    from airag import config
    return {sec: [f["key"] for f in fields] for sec, fields in config.GENERAL_SCHEMA.items()}


def build():
    from airag import runs
    from airag.llm import tasks
    en = json.loads((ROOT / "web" / "i18n" / "en.json").read_text(encoding="utf-8"))
    return {
        "python": py_modules(), "routes": routes(), "js": js_modules(), "settings": settings(),
        "job_limits": dict(getattr(runs, "LIMITS", {})), "tool_kinds": list(getattr(runs, "TOOL_KINDS", [])),
        "ai_tasks": list(tasks.TASKS), "i18n_keys": len(en),
    }


def markdown(m):
    L = ["# AIRAG code map", "", "Generated by `python tools/codemap.py`. Look things up here before calling, renaming",
         "or removing them.", "", "## HTTP routes", ""]
    L += [f"- `{meth} {path}`" for meth, path in m["routes"]]
    L += ["", "## Python modules", ""]
    for mod, info in m["python"].items():
        items = info.get("items", [])
        if not items:
            continue
        L.append(f"### {mod}")
        for it in items:
            if it["kind"] == "class":
                L.append(f"- class `{it['name']}` ({', '.join(it['methods'][:12])}{'…' if len(it['methods']) > 12 else ''})")
            elif not it["name"].startswith("_"):
                L.append(f"- {it['kind']} `{it['name']}({', '.join(it['args'])})`")
        L.append("")
    L += ["## JS modules", ""]
    for mod, info in m["js"].items():
        L.append(f"- `{mod}`: {', '.join(info['exports']) or '(no exports)'}")
    L += ["", "## Settings sections", ""]
    L += [f"- `{sec}`: {', '.join(keys)}" for sec, keys in m["settings"].items()]
    L += ["", f"Job limits: {m['job_limits']}  ", f"Tool job kinds: {', '.join(m['tool_kinds'])}  ",
          f"AI tasks: {', '.join(m['ai_tasks'])}  ", f"i18n keys (en): {m['i18n_keys']}", ""]
    return "\n".join(L)


if __name__ == "__main__":
    m = build()
    (ROOT / "codemap.json").write_text(json.dumps(m, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    (ROOT / "CODEMAP.md").write_text(markdown(m), encoding="utf-8")
    print(f"codemap: {len(m['python'])} Python modules, {len(m['routes'])} routes, {len(m['js'])} JS modules")
